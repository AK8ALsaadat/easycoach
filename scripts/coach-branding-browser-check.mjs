// Run against an isolated local development database (LOCAL_DB_PATH), never against production.
import { chromium } from "@playwright/test";
import assert from "node:assert/strict";
import sharp from "sharp";
import { mkdir } from "node:fs/promises";
import path from "node:path";
const base = process.env.TEST_BASE_URL ?? "http://127.0.0.1:3215";
const output = path.resolve("artifacts/coach-branding");
await mkdir(output, { recursive: true });
process.env.TEMP = output; process.env.TMP = output;
const browser = await chromium.launch({ headless: true, ...(process.platform === "win32" ? { channel: "msedge" } : {}) });
const errors = [];
async function login(email) {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(base + "/login");
  await page.locator("#auth-email").fill(email);
  await page.locator("#auth-password").fill("CoachPreview!2026");
  await page.locator("button[type=submit]").click();
  await page.waitForURL(email === "trainee@example.test" ? "**/me" : "**/coach");
  return page;
}
try {
  const page = await login("coach@example.test");
  await page.goto(base + "/coach/settings");
  const settings = page.locator("section", { has: page.locator("#coach-branding-heading") });
  const name = "الكابتن أحمد · هوية الاختبار";
  await settings.getByLabel("الاسم الظاهر للمتدربين").fill(name);
  const image = await sharp({ create: { width: 900, height: 1200, channels: 3, background: "#3978d4" } }).jpeg().withExif({ IFD0: { Artist: "Private metadata" } }).toBuffer();
  await settings.getByLabel("صورة المدرب", { exact: true }).setInputFiles({ name: "portrait.jpg", mimeType: "image/jpeg", buffer: image });
  await settings.getByRole("button", { name: "حفظ الهوية", exact: true }).click();
  await settings.getByRole("status").filter({ hasText: "تم حفظ هويتك" }).waitFor();
  await page.reload();
  assert.equal(await settings.getByLabel("الاسم الظاهر للمتدربين").inputValue(), name);
  const assetPath = await settings.getByAltText("معاينة صورة المدرب").getAttribute("src");
  assert(assetPath.startsWith("/api/coach-avatar/"));
  const photo = await page.request.get(base + assetPath);
  assert.equal(photo.status(), 200);
  const meta = await sharp(await photo.body()).metadata();
  assert.equal(meta.width, 512); assert.equal(meta.height, 512); assert.equal(meta.exif, undefined);
  await page.screenshot({ path: output + "/settings-desktop.png", fullPage: true });
  await page.getByRole("button", { name: "إنشاء رابط طلب انضمام", exact: true }).click();
  const joinUrl = await page.locator("#generated-join").inputValue();
  const anonymous = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const visitor = await anonymous.newPage();
  await visitor.goto(joinUrl);
  await visitor.getByLabel("هوية المدرب").getByText(name, { exact: true }).waitFor();
  assert((await visitor.locator('meta[property="og:title"]').getAttribute("content")).includes(name));
  assert((await visitor.locator('meta[property="og:image"]').getAttribute("content")).endsWith(assetPath));
  await visitor.screenshot({ path: output + "/join-mobile.png", fullPage: true });
  assert(await visitor.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  const exported = await (await page.request.get(base + "/api/export")).json();
  const client = exported.clients.find(c => c.email === "trainee@example.test");
  assert(client);
  await page.goto(base + `/coach/clients/${client.id}?tab=profile`);
  page.on("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: /تفعيل رابط العميل|تغيير الرابط والرمز/ }).click();
  const portalUrl = await page.getByLabel("رابط العميل الخاص").inputValue();
  const pin = await page.locator(".portal-share strong").innerText();
  await page.getByRole("button", { name: "إنشاء دعوة آمنة", exact: true }).click();
  const inviteUrl = await page.locator("#generated-invite").inputValue();
  await visitor.goto(inviteUrl);
  await visitor.getByLabel("هوية المدرب").getByText(name, { exact: true }).waitFor();
  assert((await visitor.locator('meta[property="og:image"]').getAttribute("content")).endsWith(assetPath));
  await visitor.goto(portalUrl);
  await visitor.getByLabel("هوية المدرب").getByText(name, { exact: true }).waitFor();
  assert.equal(await visitor.locator(".client-portal").count(), 0, "Branding must not bypass the existing PIN gate");
  await visitor.getByLabel("رمز دخول العميل").fill(pin.trim());
  await visitor.getByRole("button", { name: "افتح جدولي", exact: true }).click();
  await visitor.locator(".client-portal").waitFor();
  await visitor.getByLabel("هوية المدرب").getByText(name, { exact: true }).waitFor();
  assert(await visitor.locator('[aria-label="هوية المدرب"] img').evaluate(img => img.complete && img.naturalWidth === 512));
  await visitor.screenshot({ path: output + "/portal-mobile.png", fullPage: true });
  assert(await visitor.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  const trainee = await login("trainee@example.test");
  await trainee.getByLabel("هوية المدرب").getByText(name, { exact: true }).waitFor();
  const other = await login("coach2@example.test");
  await other.goto(base + "/coach/settings");
  assert.equal(await other.getByLabel("الاسم الظاهر للمتدربين").inputValue(), "");
  await page.goto(base + "/coach/settings");
  await settings.getByRole("button", { name: "استخدام الصورة الافتراضية" }).click();
  await settings.getByRole("button", { name: "حفظ الهوية", exact: true }).click();
  await settings.getByRole("status").filter({ hasText: "تم حفظ هويتك" }).waitFor();
  assert.equal((await page.request.get(base + assetPath)).status(), 404);
  await visitor.reload();
  await visitor.getByLabel("هوية المدرب").getByText(name, { exact: true }).waitFor();
  assert.equal(await visitor.locator('[aria-label="هوية المدرب"] img').getAttribute("src"), "/coach-avatar.svg");
  await visitor.goto(base + "/p/" + "0".repeat(64));
  assert.equal(await visitor.getByLabel("هوية المدرب").count(), 0);
  assert.equal(errors.length, 0, errors.join("\n"));
  console.log("PASS: persisted name/photo; sanitized image; join/invite/portal OG; mobile RTL/no overflow; PIN unchanged; linked account; coach isolation; image removal and invalid links.");
} finally { await browser.close(); }
